export function courseQuizQuestions(courseId: string): CourseQuizQuestion[] {
  const selected = seeds[courseId] || seeds.owasp;
  return selected.map(([question, answer], index) => {
    const correct = index % 4;
    const options = [...distractors];
    options.splice(correct, 0, answer);
    return { question, options, correct };
  });
}
