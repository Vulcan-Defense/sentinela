export function moduleStudyPack(moduleId: string): ModuleStudy | undefined {
  return moduleStudy[moduleId];
}

export function studyChapters(courseId: string, moduleTitle: string, moduleId?: string) {
  if (moduleId && moduleStudy[moduleId]) return moduleStudy[moduleId].chapters;
  const pack = packs[courseId];
  if (!pack) return null;
  return [
    {
      title: `Fundamentos de ${moduleTitle}`,
      text: `Na trilha ${pack.trail}, ${moduleTitle} entra como competência operacional — não como ferramenta isolada. Você vai situar o ativo, o dono, o impacto de uma falha e o controle mínimo que precisa existir antes de automatizar. O laboratório usa apenas ${pack.lab}.`,
    },
    {
      title: `Como reconhecer o desvio em ${moduleTitle}`,
      text: `No cenário sintético, o sinal típico de ${moduleTitle} é ${pack.signal}. Compare o comportamento esperado com o observado, registre evidência reproduzível e não saia do ambiente isolado. Separe causa, sintoma e ruído.`,
    },
    {
      title: `Como operar ${moduleTitle} com controle`,
      text: `A correção de ${moduleTitle} combina ${pack.control}. Aplique no servidor ou na declaração de infraestrutura, teste o fluxo legítimo e o caso negativo, e só então considere o módulo concluído. Documente o risco residual e o alerta que provaria regressão.`,
    },
  ];
}
